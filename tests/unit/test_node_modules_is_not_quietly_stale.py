"""A checkout whose node_modules is missing a DECLARED dependency must say so here.

The trap, measured 2026-08-20: `@axe-core/playwright`, `react-markdown` and `remark-gfm` are
declared in `store_platform/src/Ops.Console/package.json` and were absent from `node_modules` in
this worktree and in the main checkout. 448 entries were present in both, so it read as installed.

What it costs, and why a test rather than a note. The commit gate's console lane dies on
typecheck, kill-fast then SKIPS the python lane, and the operator is handed three module errors
about files they never touched. It is invisible until a diff stops being python-only, so it waits
for the worst moment. CI never sees it, because CI installs fresh — which is exactly why nothing
caught it for as long as it existed.

Two things this test refuses to do, both deliberate:

  * It SKIPS when node_modules is absent entirely. That is the documented, supported setup —
    `scripts/setup_worktree.sh` leaves it out for a python-only worktree on purpose, because the
    `cp -Rc` clone is the slow part. "Not installed" is a choice; "installed and incomplete" is
    the defect.
  * It does not grade `optionalDependencies`. `fsevents` is legitimately absent off macOS, and a
    test that fails on a platform difference gets deleted rather than fixed.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]

#: Every npm project in the tree. A new one is picked up by adding its package.json here, which
#: is a deliberate one-line cost — a glob would wander into node_modules itself.
PROJECTS = [
    REPO / "store_platform/src/Ops.Console",
]


def _declared(pkg: dict) -> set[str]:
    """Everything the project says it needs at build or test time.

    `optionalDependencies` is excluded on purpose: absent is a legal state for one.
    """
    out: set[str] = set()
    for section in ("dependencies", "devDependencies"):
        out |= set((pkg.get(section) or {}).keys())
    return out


def _show(path: Path) -> str:
    """A path relative to the repo when it is inside it, absolute when it is not.

    The mutation proof below builds a fake project under `tmp_path`, which is NOT under the
    repo, and `Path.relative_to` raises `ValueError` rather than returning something readable.
    The first run of this file failed on exactly that: the assertion message builder threw
    before the assertion it was describing could.
    """
    try:
        return str(path.relative_to(REPO))
    except ValueError:
        return str(path)


def check_installed(project: Path) -> None:
    """Skip, pass or fail one npm project. Shared so the mutation proof grades the real logic."""
    manifest = project / "package.json"
    if not manifest.exists():
        pytest.skip(f"no package.json at {_show(manifest)}")

    modules = project / "node_modules"
    if not modules.is_dir():
        # A python-only worktree by design. Nothing is stale, because nothing is installed.
        pytest.skip(
            f"{_show(modules)} is absent — a python-only worktree, which is a supported setup. "
            "This test grades an installation that LOOKS complete."
        )

    pkg = json.loads(manifest.read_text())
    missing = sorted(name for name in _declared(pkg) if not (modules / name).exists())

    assert not missing, (
        f"{len(missing)} declared dependenc{'y is' if len(missing) == 1 else 'ies are'} missing "
        f"from {_show(modules)}, which holds {sum(1 for _ in modules.iterdir())} entries and so "
        f"reads as installed: {', '.join(missing)}.\n"
        "The commit gate's console lane will die on typecheck with 'Cannot find module' errors "
        "naming files that are not in your diff, and kill-fast will then SKIP the python lane, "
        "so the gate will tell you nothing about your actual change.\n"
        f"Fix: cd {_show(project)} && npm install --no-audit --no-fund\n"
        "It takes about two minutes and leaves package-lock.json byte-identical."
    )


@pytest.mark.parametrize("project", PROJECTS, ids=lambda p: p.name)
def test_every_declared_dependency_is_actually_installed(project: Path):
    check_installed(project)


def test_this_test_knows_the_difference_between_absent_and_incomplete(tmp_path):
    """Mutation proof, on a fake project, so the guard cannot pass vacuously.

    Three states, three different answers. If any two of them ever agree, the guard is not
    grading the thing it was written for.
    """
    project = tmp_path / "fake"
    project.mkdir()
    (project / "package.json").write_text(json.dumps({
        "dependencies": {"present-one": "^1.0.0", "absent-one": "^2.0.0"},
        "optionalDependencies": {"platform-only": "^3.0.0"},
    }))

    # 1. node_modules absent -> skipped, not failed.
    with pytest.raises(BaseException) as absent:
        check_installed(project)
    assert absent.typename == "Skipped", absent.typename

    # 2. node_modules present but incomplete -> FAILS, and names the missing one only.
    modules = project / "node_modules"
    (modules / "present-one").mkdir(parents=True)
    with pytest.raises(AssertionError) as incomplete:
        check_installed(project)
    assert "absent-one" in str(incomplete.value)
    assert "present-one" not in str(incomplete.value).split("missing from")[0]
    assert "platform-only" not in str(incomplete.value), (
        "an optionalDependency was graded; this test will now fail on a platform difference"
    )

    # 3. complete -> passes.
    (modules / "absent-one").mkdir()
    check_installed(project)
