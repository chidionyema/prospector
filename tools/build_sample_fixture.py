"""Build the storefront's free-sample fixture FROM a real pack, through the real renderers.

WHY THIS TOOL EXISTS
--------------------
`/sample` is the page that tells a visitor what they get for their money, and until 2026-08-15
it was backed by a hand-maintained JSON blob (`Store.Web/src/data/sample-report.json`) whose
own dossier is no longer on disk::

    $ ls store/dossiers/0f2109fb198341a4.pass.json
    ls: no such file

So the page promising "exactly as a buyer receives it" was showing something no buyer could
receive and nothing could re-derive. That is the drift this tool removes: the fixture is now
GENERATED by the same modules that build the bundle, so a change to the pack changes the
sample, and a sample that has gone stale is a failing regeneration rather than a silent lie.

WHAT IT EMITS
-------------
The first three sections of the reading order, in full, as structured blocks -- plus the NAMES
of the eleven it does not show. The founder chose that boundary on 2026-08-15 over giving away
a whole pack: an excerpt that stops in a visible place is honest, where "a whole report, free,
nothing held back" sitting above a footer that admits a pack "adds the build spec, the go to
market plan, and the operations playbook" was not (`sample.tsx:174` against `:389`).

BLOCKS AND NODES, NOT MARKDOWN AND NOT HTML
-------------------------------------------
The storefront renders no markdown (it would print `**bold**` literally), and handing it a blob
of HTML would put the pack's styling in charge of a page that has its own -- and would make the
one page arguing "we do not overclaim" the page with five `react/no-danger` suppressions on it.

So this emits two levels of typed data and no markup at all. A section is a list of BLOCKS --
`p`, `h2`, `h3`, `hr`, `ul`, `callout`, `source` -- and a block's inline formatting is a list of
NODES: bare strings, and `{"tag": "strong"|"em"|"a"|"code", "children": [...]}`. The page builds
React elements from those. `_InlineTree` RAISES on any tag outside that set rather than stripping
it, because the one thing this file must never do is widen what the storefront renders.

Run it from the worktree, pointing at wherever the dossiers live::

    python tools/build_sample_fixture.py <pack_id> \
        --dossier-dir /Users/…/prospector/store/dossiers \
        --out /Users/…/Store.Web/src/data/sample-report.json
"""
