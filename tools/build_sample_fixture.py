#: The three sections the sample shows, in reading order. Named by FILENAME so this list and
#: `bridge.BUNDLE_READING_ORDER` cannot silently disagree about what section three is -- the
#: check below fails the build if they do.
SHOWN = ("00_Executive_Summary.md", "The_Offer.md", "The_Field.md")

#: What each withheld section is, in the buyer's terms. These describe the SECTION, never the
#: idea, so they are claim-free and stay true across every pack: "what would sink this" is a
#: fact about the document's structure, not an assertion about the market.
